"""Turns tools/assets/ace-icon.png (the Ace app icon) into main/img_ace.c (LVGL RGB565 images).

The shield is cut out of the navy background (transparent around it), so it sits
on the black screen and on the pop-up card. Used on the notification pop-up card.
"""
from PIL import Image, ImageDraw

def to_c(name, im):
    """RGB565 + an 8-bit alpha plane (LV_COLOR_FORMAT_RGB565A8), so it sits on any background."""
    w, h = im.size
    data = bytearray()
    for r, g, b, a in im.get_flattened_data():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))
    for r, g, b, a in im.get_flattened_data():
        data.append(a)
    rows = [", ".join(f"0x{x:02x}" for x in data[i:i + 24]) for i in range(0, len(data), 24)]
    body = ",\n    ".join(rows)
    return f"""
static const uint8_t {name}_map[] = {{
    {body}
}};

const lv_image_dsc_t {name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565A8,
        .w = {w},
        .h = {h},
        .stride = {w * 2},
    }},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
}};
"""

SRC = "tools/assets/ace-icon.png"
OUT = "main/img_ace.c"
SIZES = {"img_ace_small": 48}   # height in pixels (the pop-up card)
CROP = (116, 104, 396, 420)

def cut_out():
    im = Image.open(SRC).convert("RGB").crop(CROP)
    # flood the background from the corners; the white shield outline stops it
    w, h = im.size
    mask = Image.new("L", im.size, 255)
    src, m = im.load(), mask.load()
    stack = [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]
    while stack:
        x, y = stack.pop()
        if x < 0 or y < 0 or x >= w or y >= h or m[x, y] == 0:
            continue
        r, g, b = src[x, y]
        if min(r, g, b) > 120:      # reached the white outline
            continue
        m[x, y] = 0
        stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    out = im.convert("RGBA")
    out.putalpha(mask)
    return out

if __name__ == "__main__":
    ace = cut_out()
    ace.save("tools/assets/ace-cutout.png")
    parts = ["/* Generated by tools/make_ace.py from the Ace app icon. Do not edit. */\n#include \"lvgl.h\"\n"]
    for name, hgt in SIZES.items():
        wid = round(ace.size[0] * hgt / ace.size[1])
        parts.append(to_c(name, ace.resize((wid, hgt), Image.LANCZOS)))
    open(OUT, "w").write("".join(parts))
    print("wrote", OUT)
