"""The round DevX logo for the middle of the watch face (Face D): main/img_devx_round.c

tools/assets/devx-logo.png (the real app logo: white D, blue triangles, blue glow) cropped
round, with a soft Electric-blue halo drawn into the picture's edge (so the watch doesn't have
to draw a glow itself). RGB565 + alpha.
"""
from PIL import Image, ImageDraw, ImageFilter
import sys
sys.path.insert(0, "tools")
from make_ace import to_c   # run from the repo folder: python3 tools/make_face_logo.py

SRC = "tools/assets/devx-logo.png"
OUT = "main/img_devx_round.c"
LOGO = 186          # logo diameter on the watch
HALO = 14           # glow around it
K = 4               # draw bigger, then shrink (smooth edges)

def build():
    size = LOGO + 2 * HALO
    big = size * K
    out = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    # halo: a blurred blue disc behind the logo
    glow = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(glow)
    pad = HALO * K
    d.ellipse([pad - 4 * K, pad - 4 * K, big - pad + 4 * K, big - pad + 4 * K], fill=(0x3F, 0xB8, 0xFF, 110))
    glow = glow.filter(ImageFilter.GaussianBlur(HALO * K * 0.45))
    out = Image.alpha_composite(out, glow)
    # the logo, cropped round
    logo = Image.open(SRC).convert("RGBA").resize((LOGO * K, LOGO * K), Image.LANCZOS)
    m = Image.new("L", logo.size, 0)
    ImageDraw.Draw(m).ellipse([0, 0, logo.size[0] - 1, logo.size[1] - 1], fill=255)
    logo.putalpha(m)
    out.alpha_composite(logo, (pad, pad))
    return out.resize((size, size), Image.LANCZOS)

if __name__ == "__main__":
    im = build()
    im.save("tools/assets/devx-round-face.png")
    open(OUT, "w").write("/* Generated by tools/make_face_logo.py from the DevX logo. Do not edit. */\n#include \"lvgl.h\"\n" + to_c("img_devx_round", im))
    print("wrote", OUT, im.size)
