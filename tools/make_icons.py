"""Small icons, drawn here (no image files): main/img_icons.c
  img_people  two people (the "in gym now" count), Electric blue, 20 x 20
  img_bulb / img_fan / img_snow / img_plug / img_gate   switch tiles, white 28 x 28
                (tinted on the watch: dark on a lit tile, grey when off)
"""
from PIL import Image, ImageDraw
import sys
sys.path.insert(0, "tools")
from make_ace import to_c

BLUE = (0x3F, 0xB8, 0xFF, 255)

def people(size=20, k=8):
    s = size * k
    im = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    w = int(2.2 * k)
    # back person (right)
    d.ellipse([s * 0.58, s * 0.18, s * 0.86, s * 0.46], outline=BLUE, width=w)
    d.arc([s * 0.50, s * 0.56, s * 1.06, s * 1.20], 200, 340, fill=BLUE, width=w)
    # front person (left)
    d.ellipse([s * 0.14, s * 0.12, s * 0.50, s * 0.48], outline=BLUE, width=w)
    d.arc([s * 0.00, s * 0.58, s * 0.66, s * 1.30], 195, 345, fill=BLUE, width=w)
    return im.resize((size, size), Image.LANCZOS)

WHITE = (255, 255, 255, 255)

def canvas(size, k):
    s = size * k
    im = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    return im, ImageDraw.Draw(im), s

def bulb(size=28, k=8):
    im, d, s = canvas(size, k)
    w = int(2.4 * k)
    d.ellipse([s * 0.22, s * 0.06, s * 0.78, s * 0.62], outline=WHITE, width=w)
    d.rectangle([s * 0.36, s * 0.60, s * 0.64, s * 0.62 + w], fill=(0, 0, 0, 0))
    d.line([s * 0.36, s * 0.56, s * 0.36, s * 0.74], fill=WHITE, width=w)
    d.line([s * 0.64, s * 0.56, s * 0.64, s * 0.74], fill=WHITE, width=w)
    d.line([s * 0.36, s * 0.76, s * 0.64, s * 0.76], fill=WHITE, width=w)
    d.line([s * 0.40, s * 0.88, s * 0.60, s * 0.88], fill=WHITE, width=w)
    return im.resize((size, size), Image.LANCZOS)

def fan(size=28, k=8):
    im, d, s = canvas(size, k)
    c = s / 2
    for ang in (0, 120, 240):
        import math
        a = math.radians(ang)
        cx, cy = c + math.cos(a) * s * 0.23, c + math.sin(a) * s * 0.23
        r = s * 0.2
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=WHITE)
    d.ellipse([c - s * 0.09, c - s * 0.09, c + s * 0.09, c + s * 0.09], fill=(0, 0, 0, 0))
    d.ellipse([c - s * 0.05, c - s * 0.05, c + s * 0.05, c + s * 0.05], fill=WHITE)
    return im.resize((size, size), Image.LANCZOS)

def snow(size=28, k=8):
    import math
    im, d, s = canvas(size, k)
    c, w = s / 2, int(2.4 * k)
    for ang in (90, 30, 150):
        a = math.radians(ang)
        dx, dy = math.cos(a) * s * 0.42, math.sin(a) * s * 0.42
        d.line([c - dx, c - dy, c + dx, c + dy], fill=WHITE, width=w)
        for sgn in (1, -1):
            ex, ey = c + sgn * dx * 0.62, c + sgn * dy * 0.62
            for off in (40, -40):
                b = a + math.radians(off) + (0 if sgn > 0 else math.pi)
                d.line([ex, ey, ex + math.cos(b) * s * 0.14, ey + math.sin(b) * s * 0.14], fill=WHITE, width=w)
    return im.resize((size, size), Image.LANCZOS)

def plug(size=28, k=8):
    im, d, s = canvas(size, k)
    w = int(2.4 * k)
    d.line([s * 0.38, s * 0.08, s * 0.38, s * 0.30], fill=WHITE, width=w)
    d.line([s * 0.62, s * 0.08, s * 0.62, s * 0.30], fill=WHITE, width=w)
    d.rounded_rectangle([s * 0.22, s * 0.30, s * 0.78, s * 0.62], radius=s * 0.1, outline=WHITE, width=w)
    d.line([s * 0.50, s * 0.62, s * 0.50, s * 0.92], fill=WHITE, width=w)
    return im.resize((size, size), Image.LANCZOS)

def gate(size=28, k=8):
    im, d, s = canvas(size, k)
    w = int(2.4 * k)
    d.line([s * 0.10, s * 0.48, s * 0.50, s * 0.14, s * 0.90, s * 0.48], fill=WHITE, width=w, joint="curve")
    d.line([s * 0.20, s * 0.40, s * 0.20, s * 0.88, s * 0.80, s * 0.88, s * 0.80, s * 0.40], fill=WHITE, width=w, joint="curve")
    d.line([s * 0.42, s * 0.88, s * 0.42, s * 0.62, s * 0.58, s * 0.62, s * 0.58, s * 0.88], fill=WHITE, width=w, joint="curve")
    return im.resize((size, size), Image.LANCZOS)

if __name__ == "__main__":
    parts = ["/* Generated by tools/make_icons.py. Do not edit. */\n#include \"lvgl.h\"\n"]
    im = people()
    im.save("tools/assets/people.png")
    parts.append(to_c("img_people", im))
    for name, fn in (("img_bulb", bulb), ("img_fan", fan), ("img_snow", snow), ("img_plug", plug), ("img_gate", gate)):
        ic = fn()
        ic.save("tools/assets/" + name[4:] + ".png")
        parts.append(to_c(name, ic))
    open("main/img_icons.c", "w").write("".join(parts))
    print("wrote main/img_icons.c")
