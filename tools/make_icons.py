"""Small icons for the watch face, drawn here (no image files): main/img_icons.c
  img_people  two people (the "in gym now" count), Electric blue, 20 x 20
"""
from PIL import Image, ImageDraw
import sys
sys.path.insert(0, "tools")
from make_ace import to_c

BLUE = (0x3F, 0xB8, 0xFF, 255)

def people(size=20, k=8):
    s = size * k
    im = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    w = int(2.2 * k)
    # back person (right)
    d.ellipse([s * 0.58, s * 0.18, s * 0.86, s * 0.46], outline=BLUE, width=w)
    d.arc([s * 0.50, s * 0.56, s * 1.06, s * 1.20], 200, 340, fill=BLUE, width=w)
    # front person (left)
    d.ellipse([s * 0.14, s * 0.12, s * 0.50, s * 0.48], outline=BLUE, width=w)
    d.arc([s * 0.00, s * 0.58, s * 0.66, s * 1.30], 195, 345, fill=BLUE, width=w)
    return im.resize((size, size), Image.LANCZOS)

if __name__ == "__main__":
    im = people()
    im.save("tools/assets/people.png")
    open("main/img_icons.c", "w").write("/* Generated by tools/make_icons.py. Do not edit. */\n#include \"lvgl.h\"\n" + to_c("img_people", im))
    print("wrote main/img_icons.c")
