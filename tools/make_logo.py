"""Turns tools/assets/devx-logo.png into main/img_devx_logo.c (LVGL RGB565 images).

The DevX "D" mark is cut out of its blue gradient square and put on pure black,
so it blends into the AMOLED background. Two sizes: splash and header.
"""
from PIL import Image, ImageFilter

SRC = "tools/assets/devx-logo.png"
OUT = "main/img_devx_logo.c"
SIZES = {"img_devx_logo_big": 150, "img_devx_logo_small": 30}
CROP = (100, 104, 412, 404)   # around the D mark in the 512 x 512 source

def cut_out():
    im = Image.open(SRC).convert("RGB").crop(CROP)
    mask = Image.new("L", im.size, 0)
    src, m = im.load(), mask.load()
    for y in range(im.size[1]):
        for x in range(im.size[0]):
            r, g, b = src[x, y]
            white = min(r, g, b) > 170
            tri = r < 15 and g > 45 and b > 180     # bright blue triangles
            if white or tri:
                m[x, y] = 255
    mask = mask.filter(ImageFilter.MedianFilter(5))   # fill specks
    out = Image.composite(im, Image.new("RGB", im.size, (0, 0, 0)), mask)
    # square canvas, mark centred
    s = max(out.size)
    sq = Image.new("RGB", (s, s), (0, 0, 0))
    sq.paste(out, ((s - out.size[0]) // 2, (s - out.size[1]) // 2))
    return sq

def to_c(name, im):
    w, h = im.size
    data = bytearray()
    for r, g, b in im.get_flattened_data():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))
    rows = [", ".join(f"0x{x:02x}" for x in data[i:i + 24]) for i in range(0, len(data), 24)]
    body = ",\n    ".join(rows)
    return f"""
static const uint8_t {name}_map[] = {{
    {body}
}};

const lv_image_dsc_t {name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565,
        .w = {w},
        .h = {h},
        .stride = {w * 2},
    }},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
}};
"""

if __name__ == "__main__":
    mark = cut_out()
    mark.save("tools/assets/devx-logo-cutout.png")
    parts = ["/* Generated by tools/make_logo.py from the DevX logo. Do not edit. */\n#include \"lvgl.h\"\n"]
    for name, px in SIZES.items():
        img = mark.resize((px, px), Image.LANCZOS)
        img.save(f"tools/assets/{name}.png")
        parts.append(to_c(name, img))
    open(OUT, "w").write("".join(parts))
    print("wrote", OUT)
