#!/usr/bin/env python3
"""Generate main/font_time_86.c: Montserrat Medium 86 px, digits + ':' + '-' only, 4 bpp (LVGL 9).
Usage: python3 tools/make_time_font.py path/to/Montserrat-Medium.ttf"""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1]
SIZE = 86
NAME = "font_time_86"
CHARS = "-0123456789:"

font = ImageFont.truetype(TTF, SIZE)
ascent, descent = font.getmetrics()

bitmap = []
glyphs = []
PAD = SIZE
for ch in CHARS:
    canvas = Image.new("L", (SIZE * 3, SIZE * 3), 0)
    base_y = PAD + ascent
    ImageDraw.Draw(canvas).text((PAD, base_y), ch, font=font, fill=255, anchor="ls")
    x0, y0, x1, y1 = canvas.getbbox()  # tight ink box
    img = canvas.crop((x0, y0, x1, y1))
    w, h = img.size
    px = list(img.tobytes())  # 8-bit grey
    start = len(bitmap)
    nib = [p >> 4 for p in px]
    if len(nib) % 2:
        nib.append(0)
    for i in range(0, len(nib), 2):
        bitmap.append((nib[i] << 4) | nib[i + 1])
    glyphs.append(dict(ch=ch, idx=start, adv=round(font.getlength(ch) * 16), w=w, h=h,
                       ox=x0 - PAD, oy=base_y - y1))

base = ord(CHARS[0])
codes = sorted(ord(c) for c in CHARS)
assert [ord(c) for c in CHARS] == codes
out = []
out.append('/* Generated by tools/make_time_font.py: Montserrat Medium %d px, "%s" */' % (SIZE, CHARS))
out.append('#include "lvgl.h"\n')
out.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
for i in range(0, len(bitmap), 16):
    out.append("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 16]) + ",")
out.append("};\n")
out.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
out.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
for g in glyphs:
    out.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}, /* '%s' */"
               % (g["idx"], g["adv"], g["w"], g["h"], g["ox"], g["oy"], g["ch"]))
out.append("};\n")
out.append("static const uint16_t unicode_list[] = {" + ", ".join(str(c - base) for c in codes) + "};\n")
out.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
out.append("    {.range_start = %d, .range_length = %d, .glyph_id_start = 1, .unicode_list = unicode_list,"
           " .glyph_id_ofs_list = NULL, .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}"
           % (base, codes[-1] - base + 1, len(codes)))
out.append("};\n")
out.append("""static const lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
};
""")
out.append("""const lv_font_t %s = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = %d,
    .base_line = %d,
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -6,
    .underline_thickness = 4,
    .dsc = &font_dsc,
};""" % (NAME, ascent + descent, descent))
open("main/%s.c" % NAME, "w").write("\n".join(out) + "\n")
print("bytes", len(bitmap), "line_height", ascent + descent, "base", descent)
for g in glyphs: print(g)
