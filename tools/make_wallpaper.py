"""Watch face wallpaper (Logo Core face): faint weight plates and circuit lines like the DevX
website, with the round DevX logo, its glow and the steps-ring track drawn in.
One opaque picture: the watch draws it like the startup logo (no see-through blending, no RAM).
Output: tools/assets/wallpaper.png (and main/img_wallpaper.c with --c)
"""
import math, sys
from PIL import Image, ImageDraw, ImageFilter, ImageFont

W, H, K = 410, 502, 3
CX, CY = 205, 277          # logo / ring centre
RING_R, RING_W = 108, 12   # steps ring (track drawn here, progress drawn by the watch)
LOGO = 186

BLUE = (63, 184, 255)
AMBER = (255, 181, 71)

def s(v): return int(round(v * K))

def plate(d, cx, cy, r, col, a, label):
    c = col + (a,)
    for k in (1.0, 0.84, 0.36, 0.14):
        d.ellipse([s(cx - r * k), s(cy - r * k), s(cx + r * k), s(cy + r * k)], outline=c, width=s(2.2))
    for ang in (0, 90, 180, 270):          # the four grip ticks
        t = math.radians(ang)
        d.line([s(cx + math.cos(t) * r * 0.62), s(cy + math.sin(t) * r * 0.62),
                s(cx + math.cos(t) * r * 0.76), s(cy + math.sin(t) * r * 0.76)], fill=c, width=s(2.2))
    try:
        f = ImageFont.truetype("DejaVuSans-Bold.ttf", s(r * 0.16))
    except OSError:
        f = ImageFont.load_default()
    d.text((s(cx), s(cy - r * 0.48)), label, font=f, fill=c, anchor="mm")

def traces(d):
    c = BLUE + (52,)
    dot = BLUE + (110,)
    paths = [
        [(-5, 150), (70, 150), (88, 168), (118, 168)],
        [(-5, 214), (40, 214), (58, 196), (84, 196)],
        [(-5, 330), (52, 330), (70, 348), (96, 348)],
        [(415, 132), (360, 132), (342, 150), (318, 150)],
        [(415, 238), (372, 238), (354, 256), (330, 256)],
        [(415, 362), (350, 362), (332, 380), (312, 380)],
        [(150, -5), (150, 8), (168, 26)],
        [(270, 507), (270, 490), (252, 472), (230, 472)],
    ]
    for p in paths:
        d.line([(s(x), s(y)) for x, y in p], fill=c, width=s(1.4), joint="curve")
        x, y = p[-1]
        d.ellipse([s(x - 2.6), s(y - 2.6), s(x + 2.6), s(y + 2.6)], fill=dot)

def build():
    im = Image.new("RGBA", (W * K, H * K), (0, 0, 0, 255))
    lay = Image.new("RGBA", im.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(lay)
    plate(d, 62, 96, 140, BLUE, 40, "20 KG")
    plate(d, 356, 444, 124, AMBER, 30, "10 KG")
    traces(d)
    im = Image.alpha_composite(im, lay)
    # glow behind the logo
    glow = Image.new("RGBA", im.size, (0, 0, 0, 0))
    ImageDraw.Draw(glow).ellipse([s(CX - 104), s(CY - 104), s(CX + 104), s(CY + 104)], fill=BLUE + (120,))
    glow = glow.filter(ImageFilter.GaussianBlur(s(9)))
    im = Image.alpha_composite(im, glow)
    # ring track
    rr = RING_R + RING_W / 2       # outline grows inward: outer edge here = the watch's 228 px arc
    ImageDraw.Draw(im).ellipse([s(CX - rr), s(CY - rr), s(CX + rr), s(CY + rr)], outline=(0x13, 0x20, 0x3D, 255), width=s(RING_W))
    # the real DevX logo, cropped round
    logo = Image.open("tools/assets/devx-logo.png").convert("RGBA").resize((s(LOGO), s(LOGO)), Image.LANCZOS)
    m = Image.new("L", logo.size, 0)
    ImageDraw.Draw(m).ellipse([0, 0, logo.size[0] - 1, logo.size[1] - 1], fill=255)
    logo.putalpha(m)
    im.alpha_composite(logo, (s(CX - LOGO / 2), s(CY - LOGO / 2)))
    return im.resize((W, H), Image.LANCZOS).convert("RGB")

if __name__ == "__main__":
    im = build()
    im.save("tools/assets/wallpaper.png")
    if "--c" in sys.argv:
        sys.path.insert(0, "tools")
        from make_logo import to_c
        open("main/img_wallpaper.c", "w").write("/* Generated by tools/make_wallpaper.py. Do not edit. */\n#include \"lvgl.h\"\n" + to_c("img_wallpaper", im))
        print("wrote main/img_wallpaper.c")
    print("wrote tools/assets/wallpaper.png", im.size)
